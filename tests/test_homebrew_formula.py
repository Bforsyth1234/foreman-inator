"""Homebrew formula template (#38): it parses, matches pyproject, and renders.

The template is ``packaging/homebrew/foreman-inator.rb``; the renderer is
``packaging/homebrew/render_formula.py`` (loaded by path: ``packaging/`` is not a
package). ``ruby -c`` checks syntax when ruby is installed; everything else is text-level,
so no Homebrew, network or tap is needed.
"""

from __future__ import annotations

import hashlib
import importlib.util
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
HOMEBREW = REPO / "packaging" / "homebrew"
TEMPLATE = HOMEBREW / "foreman-inator.rb"
SHA = "a" * 64
PYPI_URL = "https://files.pythonhosted.org/packages/ab/cd/foreman_inator-0.2.0.tar.gz"


def _load_renderer():
    spec = importlib.util.spec_from_file_location("render_formula", HOMEBREW / "render_formula.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


rf = _load_renderer()


@pytest.fixture(scope="module")
def pyproject() -> dict:
    return tomllib.loads((REPO / "pyproject.toml").read_text())["project"]


def _rendered() -> str:
    return rf.render(TEMPLATE.read_text(), url=PYPI_URL, sha256=SHA, version="0.2.0")


def _ruby_check(tmp_path: Path, text: str) -> subprocess.CompletedProcess:
    ruby = shutil.which("ruby")
    if ruby is None:
        pytest.skip("ruby not installed")
    path = tmp_path / "foreman-inator.rb"
    path.write_text(text)
    return subprocess.run([ruby, "-c", str(path)], capture_output=True, text=True, timeout=30)


def test_template_and_rendered_formula_are_valid_ruby(tmp_path: Path) -> None:
    for text in (TEMPLATE.read_text(), _rendered()):
        result = _ruby_check(tmp_path, text)
        assert result.returncode == 0, result.stderr
        assert "Syntax OK" in result.stdout


def test_ruby_check_is_not_vacuous(tmp_path: Path) -> None:
    broken = _rendered().replace("  def install\n", "  def install(\n", 1)
    assert _ruby_check(tmp_path, broken).returncode != 0


def test_template_uses_homebrews_python_virtualenv_pattern() -> None:
    text = TEMPLATE.read_text()
    assert re.search(r"^class ForemanInator < Formula$", text, re.M)
    assert "include Language::Python::Virtualenv" in text
    assert re.search(r"def install\n\s+virtualenv_install_with_resources\n\s+end", text)
    assert re.search(r'^  depends_on "python@3\.\d+"$', text, re.M)
    # Deps taken from homebrew-core formulae must not also be resolved as resources.
    excluded = re.search(r"pypi_packages exclude_packages: %w\[([^\]]*)\]", text)
    assert excluded is not None
    for name in excluded[1].split():
        assert f'depends_on "{name}"' in text
    assert re.search(r"^  test do\n.*--version", text, re.M | re.S)
    # Resources are generated by brew, never hand-written into the template.
    assert "resource " not in text.split("class ForemanInator")[1]


def test_template_matches_pyproject(pyproject: dict) -> None:
    text = TEMPLATE.read_text()
    assert f'license "{pyproject["license"]}"' in text
    assert f'homepage "{pyproject["urls"]["Homepage"]}"' in text
    floor = re.fullmatch(r">=3\.(\d+)", pyproject["requires-python"])
    python = re.search(r'depends_on "python@3\.(\d+)"', text)
    assert floor and python and int(python[1]) >= int(floor[1])
    for script in pyproject["scripts"]:
        assert f"#{{bin}}/{script} --version" in text
    desc = re.search(r'^  desc "([^"]+)"$', text, re.M)[1]
    assert len(desc) <= 80 and not desc.lower().startswith(("a ", "an ", "foreman"))


def test_template_says_it_needs_fde_kit_on_pypi() -> None:
    assert "fde-kit is not on PyPI" in TEMPLATE.read_text()
    assert "fde-kit" in (REPO / "docs" / "homebrew.md").read_text()


def test_render_fills_both_placeholders() -> None:
    out = _rendered()
    assert f'  url "{PYPI_URL}"\n' in out
    assert f'  sha256 "{SHA}"\n' in out
    assert "@@" not in out


@pytest.mark.parametrize(
    ("kwargs", "message"),
    [
        ({"url": "http://x/foreman_inator-0.2.0.tar.gz", "sha256": SHA}, "https"),
        ({"url": "https://x/other-0.2.0.tar.gz", "sha256": SHA}, "not a foreman-inator sdist"),
        ({"url": "https://x/foreman_inator-0.2.0-py3-none-any.whl", "sha256": SHA}, "sdist"),
        ({"url": PYPI_URL, "sha256": "A" * 64}, "64 lowercase hex"),
        ({"url": PYPI_URL, "sha256": "a" * 63}, "64 lowercase hex"),
        ({"url": PYPI_URL, "sha256": SHA, "version": "0.3.0"}, "expected 0.3.0"),
        ({"url": 'https://x/"#{system}/foreman_inator-0.2.0.tar.gz', "sha256": SHA}, "characters"),
        ({"url": "https://x/a b/foreman_inator-0.2.0.tar.gz", "sha256": SHA}, "characters"),
        ({"url": "https://x/a?q=#{1}/foreman_inator-0.2.0.tar.gz", "sha256": SHA}, "characters"),
    ],
)
def test_render_rejects_bad_inputs(kwargs: dict, message: str) -> None:
    with pytest.raises(rf.RenderError, match=message):
        rf.render(TEMPLATE.read_text(), **kwargs)


def test_render_rejects_a_template_without_placeholders() -> None:
    with pytest.raises(rf.RenderError, match="exactly once"):
        rf.render('url "x"\nsha256 "y"\n', url=PYPI_URL, sha256=SHA)


def test_cli_hashes_a_local_sdist_and_defaults_to_the_github_release(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    sdist = tmp_path / "foreman_inator-0.2.0.tar.gz"
    sdist.write_bytes(b"not really a tarball")
    out = tmp_path / "Formula" / "foreman-inator.rb"
    out.parent.mkdir()
    assert rf.main(["--sdist", str(sdist), "-o", str(out)]) == 0
    text = out.read_text()
    digest = hashlib.sha256(b"not really a tarball").hexdigest()
    assert f'sha256 "{digest}"' in text
    assert (
        'url "https://github.com/Bforsyth1234/foreman-inator/releases/download/'
        'v0.2.0/foreman_inator-0.2.0.tar.gz"'
    ) in text


def test_cli_uses_the_pypi_sdist_not_the_wheel(capsys: pytest.CaptureFixture[str]) -> None:
    seen: list[str] = []

    def fake_fetch(url: str) -> dict:
        seen.append(url)
        return {
            "urls": [
                {
                    "packagetype": "bdist_wheel",
                    "url": "https://files.pythonhosted.org/x/foreman_inator-0.2.0-py3-none-any.whl",
                    "digests": {"sha256": "b" * 64},
                },
                {"packagetype": "sdist", "url": PYPI_URL, "digests": {"sha256": SHA}},
            ]
        }

    assert rf.main(["--pypi", "0.2.0"], fetch=fake_fetch) == 0
    assert seen == ["https://pypi.org/pypi/foreman-inator/0.2.0/json"]
    text = capsys.readouterr().out
    assert f'url "{PYPI_URL}"' in text and f'sha256 "{SHA}"' in text


def test_cli_fails_cleanly_when_pypi_has_no_sdist(capsys: pytest.CaptureFixture[str]) -> None:
    assert rf.main(["--pypi", "0.2.0"], fetch=lambda url: {"urls": []}) == 1
    assert "expected one sdist, found 0" in capsys.readouterr().err
